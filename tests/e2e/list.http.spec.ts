import { expect, test } from '@playwright/test';
import { BASE, BUILD, message, publicUrl } from './support/artifact';
import { feedIndex, feedPage, hasBand, localeIndex, manifest, pagePromptIds } from './support/content';
import { canonical, dataAttr, elementText, htmlElement, title } from './support/html';

// The Prompt list as crawlers receive it (design doc §9.4, §16.2 "列表与连续加载", §17.3 step 3a):
// every page address has its own cards, canonical and real links to every page, so all
// published prompts are reachable without scrolling or scripts; /page/1/ redirects and pages
// past the end answer 404.

const listPath = (prefix: string, n: number) => (n <= 1 ? `/${prefix}/prompts/` : `/${prefix}/prompts/page/${n}/`);

/** Entry IDs of the works in the feed, in document order: cards and feature rows of extreme works. */
function feedIds(html: string): string[] {
  const feed = html.slice(html.indexOf('role="feed"'));
  const attr = (tag: string, name: string) => new RegExp(`${name}="([^"]*)"`).exec(tag)?.[1];
  return [...feed.matchAll(/<article [^>]*>/g)]
    .map((m) => m[0])
    .filter((tag) => !attr(tag, 'data-interlude') || attr(tag, 'data-reason') === 'extreme')
    .map((tag) => attr(tag, 'data-entry')!);
}

const hrefs = (html: string) => [...html.matchAll(/<a [^>]*href="([^"]+)"/g)].map((m) => m[1]!.replace(/&amp;/g, '&'));

for (const locale of BUILD.locales) {
  const index = feedIndex(locale.code);

  test(`${locale.code}: the list's pages carry their cards, canonical and page links`, async ({ request }) => {
    for (let n = 1; n <= index.pageCount; n += 1) {
      const res = await request.get(`${BASE}${listPath(locale.pathPrefix, n)}`);
      expect(res.status(), `page ${n}`).toBe(200);
      const html = await res.text();
      expect(htmlElement(html)).toEqual({ lang: locale.htmlLang, dir: locale.direction });
      expect(dataAttr(html, 'page')).toBe('prompt-list');
      expect(elementText(html, 'h1')).toBe(message(locale.code, 'feed.title'));
      expect(canonical(html)).toBe(publicUrl(listPath(locale.pathPrefix, n)));
      const expectedTitle =
        n > 1
          ? message(locale.code, 'feed.documentTitlePage', { page: String(n) })
          : message(locale.code, 'feed.documentTitle');
      expect(title(html)).toBe(`${expectedTitle} · ${BUILD.siteName}`);

      // The HTML of /page/{n}/ and {n}.json come from the same data (§3.5).
      expect(feedIds(html)).toEqual(pagePromptIds(feedPage(locale.code, n)));
      // Real links to every page (§9.4) and to each work's detail page.
      const links = new Set(hrefs(html));
      for (let m = 1; m <= index.pageCount; m += 1)
        if (index.pageCount > 1)
          expect(links, `link to page ${m}`).toContain(`${BASE}${listPath(locale.pathPrefix, m)}`);
      for (const id of pagePromptIds(feedPage(locale.code, n))) {
        const p = localeIndex(locale.code).prompts.find((x) => x.id === id)!;
        expect(links, `link to ${id}`).toContain(`${BASE}${p.path}`);
      }
      // The showcase band leads page 1 only; no manual "load more" control anywhere (§11.12).
      expect(html.includes('data-band'), `band on page ${n}`).toBe(n === 1 && hasBand(locale.code));
      expect(html).not.toMatch(/load more/i);
    }
  });

  test(`${locale.code}: following page links reaches every published prompt`, async ({ request }) => {
    const seen = new Set<string>();
    const queue = [`${BASE}${listPath(locale.pathPrefix, 1)}`];
    const visited = new Set<string>();
    while (queue.length) {
      const url = queue.shift()!;
      if (visited.has(url)) continue;
      visited.add(url);
      const html = await (await request.get(url)).text();
      feedIds(html).forEach((id) => seen.add(id));
      for (const href of hrefs(html))
        if (
          href.startsWith(`${BASE}/${locale.pathPrefix}/prompts/page/`) ||
          href === `${BASE}/${locale.pathPrefix}/prompts/`
        )
          queue.push(href);
    }
    expect([...seen].sort()).toEqual(
      localeIndex(locale.code)
        .prompts.map((p) => p.id)
        .sort(),
    );
  });

  test(`${locale.code}: /page/1/ is no page of its own and pages past the end are 404`, async ({ request }) => {
    // The host redirects it to the list (§9.4); the rule comes from the manifest, and host
    // configuration from it is generated by step 3e. Until then the address is simply absent.
    expect(manifest().redirects).toContainEqual({
      from: `/${locale.pathPrefix}/prompts/page/1/`,
      to: `/${locale.pathPrefix}/prompts/`,
    });
    const res = await request.get(`${BASE}/${locale.pathPrefix}/prompts/page/1/`, { maxRedirects: 0 });
    expect([301, 308, 404]).toContain(res.status());
    if (res.status() !== 404)
      expect(new URL(res.headers().location!, 'http://x').pathname).toBe(`${BASE}/${locale.pathPrefix}/prompts/`);
    const past = await request.get(`${BASE}/${locale.pathPrefix}/prompts/page/${index.pageCount + 1}/`);
    expect(past.status()).toBe(404);
  });
}
