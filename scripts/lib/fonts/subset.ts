import crypto from 'node:crypto';
import subsetFont from 'subset-font';

// Build-time subsetting of the CJK display faces (design doc §11.1.2). The sources are
// Fontsource's variable Noto Sans slices; each slice that holds characters this build needs is
// cut down to exactly those characters at weight 700 (the display weight, --weight-display) and
// gets its own @font-face with the precise unicode-range. A page then downloads only the few
// small files its own title uses, a few kilobytes each.

/** Weight the variable source is pinned to. */
export const DISPLAY_WEIGHT = 700;

export type Range = readonly [number, number];

/** "U+4e00-4e03,U+4e08" → [[0x4e00, 0x4e03], [0x4e08, 0x4e08]]. */
export function parseUnicodeRange(css: string): Range[] {
  return css
    .split(',')
    .map((part) => part.trim().replace(/^U\+/i, ''))
    .filter(Boolean)
    .map((part) => {
      const [a, b = a] = part.split('-');
      return [parseInt(a!, 16), parseInt(b!, 16)] as const;
    });
}

/** Code points → the shortest unicode-range descriptor. */
export function formatUnicodeRange(codePoints: Iterable<number>): string {
  const sorted = [...new Set(codePoints)].sort((a, b) => a - b);
  const parts: string[] = [];
  for (let i = 0; i < sorted.length;) {
    let j = i;
    while (j + 1 < sorted.length && sorted[j + 1] === sorted[j]! + 1) j++;
    const hex = (n: number) => n.toString(16);
    parts.push(i === j ? `U+${hex(sorted[i]!)}` : `U+${hex(sorted[i]!)}-${hex(sorted[j]!)}`);
    i = j + 1;
  }
  return parts.join(',');
}

/**
 * Characters the CJK face must supply. Latin and Cyrillic come from the Latin display face
 * earlier in the stack; on CJK pages that face leaves out the em dash, curly quotes and the
 * ellipsis so they render full width (src/styles/fonts/index.ts), so those are needed too.
 */
export function cjkCharacters(texts: Iterable<string>): Set<number> {
  const out = new Set<number>();
  for (const text of texts)
    for (const ch of text) {
      const cp = ch.codePointAt(0)!;
      if (cp >= 0x2e80 || cp === 0x2014 || cp === 0x2026 || (cp >= 0x2018 && cp <= 0x201f)) out.add(cp);
    }
  return out;
}

/**
 * Assigns each character to the source slice that covers it. `slices` is Fontsource's
 * unicode.json: slice name → unicode-range. Characters no slice covers are returned apart (the
 * face lacks them; they fall back to the next font in the stack).
 */
export function planSlices(
  chars: ReadonlySet<number>,
  slices: Readonly<Record<string, string>>,
): { bySlice: Map<string, number[]>; missing: number[] } {
  const ranges = Object.entries(slices).map(([name, css]) => [name, parseUnicodeRange(css)] as const);
  const bySlice = new Map<string, number[]>();
  const missing: number[] = [];
  for (const cp of [...chars].sort((a, b) => a - b)) {
    const hit = ranges.find(([, rs]) => rs.some(([a, b]) => cp >= a && cp <= b));
    if (!hit) missing.push(cp);
    else bySlice.set(hit[0], [...(bySlice.get(hit[0]) ?? []), cp]);
  }
  return { bySlice, missing };
}

/** Fontsource file of a slice: "[42]" → noto-sans-sc-42-wght-normal.woff2. */
export const sliceFile = (id: string, slice: string) => `${id}-${slice.replace(/[[\]]/g, '')}-wght-normal.woff2`;

/** One slice cut to `codePoints`, pinned to the display weight, as WOFF2. */
export async function subsetSlice(source: Buffer, codePoints: readonly number[]): Promise<Buffer> {
  return subsetFont(source, String.fromCodePoint(...codePoints), {
    targetFormat: 'woff2',
    variationAxes: { wght: DISPLAY_WEIGHT },
  });
}

export const contentHash = (data: Uint8Array) => crypto.createHash('sha256').update(data).digest('hex').slice(0, 12);

export type FaceFile = { url: string; codePoints: readonly number[] };

/** The stylesheet for one family: one @font-face per subset file, swap while loading (§11.1.2). */
export function fontFaceCss(family: string, files: readonly FaceFile[]): string {
  const faces = files.map(
    (f) =>
      `@font-face{font-family:'${family}';font-style:normal;font-weight:${DISPLAY_WEIGHT};font-display:swap;` +
      `src:url(${f.url}) format('woff2');unicode-range:${formatUnicodeRange(f.codePoints)}}`,
  );
  return `/* Generated by content:build (display-fonts). ${family}, SIL OFL 1.1. */\n${faces.join('\n')}\n`;
}
