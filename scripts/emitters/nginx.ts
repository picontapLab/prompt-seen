import { defineEmitter } from './_types';

// Reference nginx include for serving dist/ (design doc §15.4; subpath memo §3.3, §7.3–7.4).
// The host's server block sets `root` to a copy of dist/, `absolute_redirect off` (memo §7.4
// item 3) and includes this file; see deploy/nginx/host-server.conf. Step 3e adds the
// redirect and 410 rules generated from redirects.yaml and the deleted-entry list.

const TEXT_TYPES = 'text/plain text/css text/xml application/json application/javascript text/markdown';

export default defineEmitter({
  name: 'nginx',
  description: 'deploy/generated/nginx/prompt-seen.conf: reference host include',
  run({ config, locales, url, write }) {
    const base = config.basePath;
    const internalOnly = (location: string) => `location ^~ ${location} { internal; error_page 404 ${base}/404.html; }`;
    const lines = [
      '# GENERATED by scripts/emitters/nginx.ts. Do not edit; run `npm run content:build`.',
      `# build ${config.buildId} (${config.buildMode})  basePath="${base}"  origin=${config.origin}`,
      '',
      ...(base ? [`location = ${base} { return 301 ${base}/; }`, ''] : []),
      `location ${base}/ {`,
      `    charset utf-8; charset_types ${TEXT_TYPES};`,
      `    error_page 404 ${base}/404.html;`,
      '}',
      '',
      '# The export writes extra copies of the root 404 page (trailingSlash); none may answer 200.',
      `location = ${base}/404.html { internal; error_page 404 ${base}/404.html; }`,
      internalOnly(`${base}/404/`),
      internalOnly(`${base}/_not-found/`),
      '',
      '# Markdown versions (§9.10.4): nginx has no type for .md, and the twin points at its HTML page.',
      `location ~ ^${base}/(?<ps_md_dir>.+/)index\\.md$ {`,
      '    types { }',
      '    default_type "text/markdown; charset=utf-8";',
      `    add_header Link "<${url.absoluteUrl('/')}$ps_md_dir>; rel=\\"canonical\\"" always;`,
      `    error_page 404 ${base}/404.html;`,
      '}',
      '',
      '# Per-locale error pages (§4.1); the pages themselves are internal, so they never answer 200.',
      ...locales.flatMap((l) => {
        const notFound = url.withBasePath(url.paths.notFound(l.pathPrefix));
        return [
          `location ${url.withBasePath(url.paths.home(l.pathPrefix))} {`,
          `    charset utf-8; charset_types ${TEXT_TYPES};`,
          `    error_page 404 ${notFound}index.html;`,
          '}',
          internalOnly(notFound),
          internalOnly(url.withBasePath(url.paths.gone(l.pathPrefix))),
        ];
      }),
      '',
    ];
    write('deploy', 'nginx/prompt-seen.conf', lines.join('\n'));
  },
});
