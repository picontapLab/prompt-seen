import { CLOUDFLARE_REDIRECT_LIMIT, cloudflarePayloadProxies, cloudflareRedirects, hostRules } from '../lib/hosts';
import { defineEmitter } from './_types';

// Cloudflare Pages host files (design doc §17.1: previews and production on Cloudflare Pages).
// scripts/deploy-cloudflare.ts copies them to the root of the uploaded directory. Redirects come
// from redirects.yaml and the first list page (§9.5); Pages cannot answer 410, so removed
// addresses fall back to the locale's 404 page (subpath memo §3.3).
export default defineEmitter({
  name: 'cloudflare',
  description: 'deploy/generated/cloudflare/_headers, _redirects',
  run({ config, content, locales, url, write }) {
    const headers = [
      '# GENERATED by scripts/emitters/cloudflare.ts. Do not edit.',
      ...(config.buildMode === 'preview'
        ? ['/*', '  X-Robots-Tag: noindex', '']
        : // A production deploy is also served at the project's *.pages.dev addresses, which are
          // not the canonical host (§9.3, §15.4.3). A host that forwards /prompt-seen/ to Pages
          // drops this header (deploy/hosts/), so only direct visits to pages.dev carry it.
          [
            'https://:project.pages.dev/*',
            '  X-Robots-Tag: noindex',
            '',
            'https://:version.:project.pages.dev/*',
            '  X-Robots-Tag: noindex',
            '',
          ]),
      `${url.withBasePath('/_next/static/')}*`,
      '  Cache-Control: public, max-age=31536000, immutable',
      '',
      // Markdown versions (§9.10.4): served as Markdown, with the HTML page as canonical so the
      // twin is never indexed as a duplicate. One splat rule covers every locale and kind.
      `${url.withBasePath('/')}*/index.md`,
      '  Content-Type: text/markdown; charset=utf-8',
      `  Link: <${url.absoluteUrl('/')}:splat/>; rel="canonical"`,
      '',
    ];
    write('deploy', 'cloudflare/_headers', headers.join('\n'));

    const [rootPayloadProxy, nestedPayloadProxy] = cloudflarePayloadProxies(url);
    const rules = [
      // A subpath project's root also counts toward the static redirect limit.
      ...(config.basePath ? [`/ ${url.withBasePath('/')} 302`] : []),
      ...cloudflareRedirects(hostRules(content.manifest, url, locales)),
      // The upload preparation verifies and removes duplicate full RSC payloads. Keep their
      // original URLs working through Pages' 200 proxy rules, including the root payload.
      rootPayloadProxy,
    ];
    if (rules.length > CLOUDFLARE_REDIRECT_LIMIT)
      throw new Error(
        `cloudflare: ${rules.length} redirect rules exceed the Pages limit of ${CLOUDFLARE_REDIRECT_LIMIT}; later ones would be ignored`,
      );
    const redirects = ['# GENERATED by scripts/emitters/cloudflare.ts. Do not edit.', ...rules, nestedPayloadProxy, ''];
    write('deploy', 'cloudflare/_redirects', redirects.join('\n'));
  },
});
