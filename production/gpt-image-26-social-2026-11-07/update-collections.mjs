function writeCollection(id, entry, en, zh) {
  const dir = path.join(root, 'content/collections', id);
  const entryFile = path.join(dir, 'entry.yaml');
  if (fs.existsSync(entryFile) && YAML.parse(fs.readFileSync(entryFile, 'utf8')).slug !== entry.slug)
    throw new Error(`Collection ID occupied: ${id}`);
  fs.mkdirSync(path.join(dir, 'locales'), { recursive: true });
  fs.writeFileSync(entryFile, YAML.stringify({ id, ...entry }));
  for (const [code, locale] of [
    ['en', en],
    ['zh-Hans', zh],
  ]) {
    const { body, ...front } = locale;
    const fm = {
      ...front,
      status: 'published',
      updatedAt: '2026-11-09',
      ...(code === 'en'
        ? {}
        : {
            translation: {
              sourceLocale: 'en',
              sourceHash: sourceHashOf({ fm: en, body: en.body }),
              reviewStatus: 'reviewed',
            },
          }),
    };
    fs.writeFileSync(path.join(dir, 'locales', `${code}.mdx`), `---\n${YAML.stringify(fm)}---\n\n${body}\n`);
  }
}
