// Spike stand-in for `content:build`:
//  1. public/generated/{prefix}/prompts/{slug}.json  — popup data (same model as the full page)
//  2. deploy/nginx/prompt-seen.locations.conf         — host include: 301, 410, per-locale 404, types
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import YAML from 'yaml';
import { toDetailModel } from '../src/lib/detail-model.mjs';
import { BASE_PATH, LOCALES, SITE_ORIGIN, popupJsonPath } from '../src/lib/site.mjs';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const prompts = JSON.parse(read('content/prompts.json'));
const redirects = YAML.parse(read('content/redirects.yaml'));
const deleted = YAML.parse(read('content/deleted.yaml'));

// 1. popup JSON
fs.rmSync(path.join(root, 'public/generated'), { recursive: true, force: true });
let jsonCount = 0;
for (const locale of LOCALES) {
  for (const item of prompts) {
    const file = path.join(root, 'public', popupJsonPath(locale.prefix, item.slug));
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, JSON.stringify(toDetailModel(item, locale)));
    jsonCount++;
  }
}

// 2. nginx include (server-level). Requires the host's `root` to point at the
// directory that contains `${BASE_PATH.slice(1)}/` (i.e. dist/), and
// `absolute_redirect off` so directory redirects keep the public host/port.
const B = BASE_PATH;
const bare = (p) => p.replace(/\/$/, '');
const lines = [];
const out = (s = '') => lines.push(s);
const CHARSET = 'charset utf-8; charset_types text/plain text/xml application/json text/markdown;';

out(`# GENERATED by scripts/content-build.mjs — do not edit.`);
out(`# basePath=${B}  origin=${SITE_ORIGIN}`);
out();
out(`location = ${B} { return 301 ${B}/; }`);
out();
out(`location ${B}/ {`);
out(`    ${CHARSET}`);
out(`    error_page 404 ${B}/404.html;`);
out(`}`);
out(`location = ${B}/404.html { internal; charset utf-8; error_page 404 ${B}/404.html; }`);
out(`# next export (trailingSlash) also emits 404/index.html and _not-found/index.html; keep them off 200.`);
out(`location ^~ ${B}/404/ { internal; charset utf-8; error_page 404 ${B}/404.html; }`);
out(`location ^~ ${B}/_not-found/ { internal; charset utf-8; error_page 404 ${B}/404.html; }`);
out();
out(`# Markdown twins: correct type + Link canonical to the HTML page (design doc §9.10.4).`);
out(`location ~ ^${B}/(?<ps_md_dir>.+/)index\\.md$ {`);
out(`    types { }`);
out(`    default_type "text/markdown; charset=utf-8";`);
out(`    add_header Link "<${SITE_ORIGIN}${B}/$ps_md_dir>; rel=\\"canonical\\"" always;`);
out(`    error_page 404 ${B}/404.html;`);
out(`}`);
out();
out(`# Per-locale error pages. The pages themselves are internal-only so they never answer 200.`);
for (const l of LOCALES) {
  const p = `${B}/${l.prefix}`;
  out(`location ${p}/ {`);
  out(`    ${CHARSET}`);
  out(`    error_page 404 ${p}/404/index.html;`);
  out(`}`);
  out(`location ^~ ${p}/404/ { internal; charset utf-8; error_page 404 ${p}/404/index.html; }`);
  out(`location ^~ ${p}/410/ { internal; charset utf-8; error_page 404 ${p}/404/index.html; }`);
}
out();
out(`# 301 from content/redirects.yaml (both slash forms).`);
for (const r of redirects) {
  for (const from of new Set([r.from, bare(r.from)])) {
    out(`location = ${B}${from} { return 301 ${B}${r.to}; }`);
  }
}
out();
out(`# 410 from content/deleted.yaml.`);
for (const d of deleted) {
  for (const prefix of d.locales) {
    const p = `/${prefix}/prompts/${d.slug}/`;
    for (const from of new Set([p, bare(p)])) {
      out(`location = ${B}${from} { error_page 410 ${B}/${prefix}/410/index.html; return 410; }`);
    }
  }
}

const confFile = path.join(root, 'deploy/nginx/prompt-seen.locations.conf');
fs.mkdirSync(path.dirname(confFile), { recursive: true });
fs.writeFileSync(confFile, lines.join('\n') + '\n');

console.log(
  `content:build  json=${jsonCount}  redirects=${redirects.length}  deleted=${deleted.length}  -> ${path.relative(root, confFile)}`,
);
