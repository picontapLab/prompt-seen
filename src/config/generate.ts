// Node-only: writes src/config/generated/config.ts, the resolved configuration as constants
// plus literal locale types (design doc §8.2), so app code never reads YAML or the environment.
// Called by `npm run gen` and by next.config.ts, so `next dev` and `next build` always run
// with the same configuration as the app, even when started directly.
import fs from 'node:fs';
import path from 'node:path';
import { loadConfig } from './load';
import type { ResolvedConfig } from './schema';

const union = (values: string[]) => (values.length ? values.map((v) => JSON.stringify(v)).join(' | ') : 'never');

export function writeGeneratedConfig(root: string = process.cwd()): ResolvedConfig {
  const config = loadConfig(root);
  const out = path.join(root, 'src/config/generated/config.ts');
  const source = `// GENERATED by src/config/generate.ts from content/site.yaml, content/locales.yaml
// and the environment. Do not edit; run \`npm run gen\`.
import type { ResolvedConfig } from '../schema';

export const CONFIG: ResolvedConfig = ${JSON.stringify(config, null, 2)};

/** Every registered locale code (BCP 47), used for files, messages and hreflang. */
export type LocaleCode = ${union(config.locales.map((l) => l.code))};
/** Every registered URL prefix. */
export type LocalePrefix = ${union(config.locales.map((l) => l.pathPrefix))};
/** URL prefixes generated in this build. */
export type BuiltLocalePrefix = ${union(config.builtLocales.map((l) => l.pathPrefix))};
`;
  fs.mkdirSync(path.dirname(out), { recursive: true });
  // Rewrite only on change: next.config.ts runs in several processes.
  if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== source) fs.writeFileSync(out, source);
  return config;
}
